"""Scaffold (or refresh) the dbt files that every market needs.

    python scripts/scaffold_market.py MAD

reads the market's block from dbt_project.yml (vars.markets.MAD) and the raw files in seeds/bronze/mad_*.csv, then:

  * writes the four one-line staging models in models/silver/staging/mad/
  * regenerates models/bronze/sources.yml (every bronze table, with its submission timestamp as loaded_at_field)
  * regenerates seeds/bronze/_bronze_seeds.yml (every raw column typed as string, so bronze keeps the files as sent)

Run it with no argument to refresh the two YAML files for all configured markets.
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATASETS = ("market_stats", "deals", "buildings", "availability")
MACRO = {"market_stats": "stage_market_stats", "deals": "stage_deals", "buildings": "stage_buildings", "availability": "stage_availability"}
DESCRIPTIONS = {
    "market_stats": "Quarterly market submission: stock, vacancy, take-up, prime rent and yield by submarket, in the market's own template.",
    "deals": "Leasing deal log in the market's own template: one row per transaction as submitted (resubmissions included).",
    "buildings": "Building register in the market's own template: one row per building per submission.",
    "availability": "Quarterly availability snapshot of the tracked buildings, in the market's own template.",
}


def load_markets() -> dict:
    project = yaml.safe_load((ROOT / "dbt_project.yml").read_text(encoding="utf-8"))
    return project["vars"]["markets"]


def csv_header(path: Path) -> list[str]:
    with path.open(encoding="utf-8", newline="") as f:
        return next(csv.reader(f))


def write_staging_models(market_id: str, cfg: dict):
    folder = ROOT / "models" / "silver" / "staging" / market_id.lower()
    folder.mkdir(parents=True, exist_ok=True)
    for ds in DATASETS:
        path = folder / f"stg_{market_id.lower()}__{ds}.sql"
        path.write_text(
            f"-- {cfg['market_name']} ({market_id}): {ds.replace('_', ' ')} in the shared staging layout.\n"
            f"-- All market-specific parsing is driven by vars.markets.{market_id} in dbt_project.yml.\n"
            f"{{{{ {MACRO[ds]}('{market_id}') }}}}\n",
            encoding="utf-8",
        )
        print("wrote", path.relative_to(ROOT))


def write_sources(markets: dict):
    tables = []
    for mid, cfg in markets.items():
        for ds in DATASETS:
            d = cfg[ds]
            table = {"name": d["source"], "description": f"{cfg['market_name']}: {DESCRIPTIONS[ds]}"}
            if "submitted_at" in d["columns"]:
                table["config"] = {"loaded_at_field": f"cast({d['columns']['submitted_at']} as timestamp)"}
            else:  # the building register carries a local-format date, not a portal timestamp: no freshness check
                table["config"] = {"freshness": None}
            tables.append(table)
    doc = {
        "version": 2,
        "sources": [{
            "name": "bronze",
            "description": ("Raw market submissions exactly as sent, one table per market and dataset. Loaded here as dbt seeds "
                            "(or by databricks/notebooks/01_land_bronze_from_volume.sql in a workspace). Every column is a string; "
                            "nothing is parsed or converted until the silver staging layer."),
            "schema": "bronze",
            "config": {"freshness": {"warn_after": {"count": 120, "period": "day"}}},
            "tables": tables,
        }],
    }
    path = ROOT / "models" / "bronze" / "sources.yml"
    path.write_text("# Generated by scripts/scaffold_market.py from vars.markets in dbt_project.yml. Do not edit by hand.\n"
                    + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    print("wrote", path.relative_to(ROOT))


def write_seed_config(markets: dict):
    seeds = []
    for mid, cfg in markets.items():
        for ds in DATASETS:
            name = cfg[ds]["source"]
            header = csv_header(ROOT / "seeds" / "bronze" / f"{name}.csv")
            seeds.append({
                "name": name,
                "description": f"{cfg['market_name']}: {DESCRIPTIONS[ds]}",
                "config": {"column_types": {col: "string" for col in header}},
            })
    doc = {"version": 2, "seeds": seeds}
    path = ROOT / "seeds" / "bronze" / "_bronze_seeds.yml"
    path.write_text("# Generated by scripts/scaffold_market.py: every raw column is loaded as a string. Do not edit by hand.\n"
                    + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    print("wrote", path.relative_to(ROOT))


def main():
    markets = load_markets()
    if len(sys.argv) > 1:
        mid = sys.argv[1].upper()
        if mid not in markets:
            sys.exit(f"{mid} is not configured under vars.markets in dbt_project.yml; add its block first")
        write_staging_models(mid, markets[mid])
    write_sources(markets)
    write_seed_config(markets)


if __name__ == "__main__":
    main()
